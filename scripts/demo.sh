#!/usr/bin/env bash
# One-command local demo: a production build of SEO OS on clearly labelled synthetic data.
#
#   npm run demo                 # http://localhost:3100, prints a demo login
#   npm run demo -- --reset      # drop and rebuild the demo database first
#   npm run demo -- --rebuild    # force a fresh production build
#
# It uses its own database (seo_os_demo), its own Redis index and its own throwaway secrets in
# .env.demo (git-ignored). It never reads or changes .env or your real data, and sign-up is
# disabled so the demo stays single-user.
set -euo pipefail
cd "$(dirname "$0")/.."

info() { printf '\033[36m→\033[0m %s\n' "$1"; }
ok()   { printf '\033[32m✓\033[0m %s\n' "$1"; }
fail() { printf '\033[31m✗\033[0m %s\n' "$1" >&2; exit 1; }

RESET=false; REBUILD=false
for arg in "$@"; do
  case "$arg" in
    --reset) RESET=true ;;
    --rebuild) REBUILD=true ;;
    -h|--help) sed -n '2,11p' "$0"; exit 0 ;;
    *) fail "Unknown option: $arg" ;;
  esac
done

PORT="${DEMO_PORT:-3100}"
DEMO_DB="${DEMO_DB:-seo_os_demo}"
ENV_FILE=".env.demo"

command -v node >/dev/null || fail "Node.js 20.11+ is required."
command -v openssl >/dev/null || fail "openssl is required to generate the demo secrets."

# ── Find Postgres ────────────────────────────────────────────────────────────
# DEMO_DATABASE_URL wins. Otherwise try the docker-compose credentials, then the local OS user
# (Homebrew / Postgres.app default).
pg_works() { command -v psql >/dev/null && psql "$1" -tAc 'select 1' >/dev/null 2>&1; }
if [ -n "${DEMO_DATABASE_URL:-}" ]; then
  DATABASE_URL="$DEMO_DATABASE_URL"
else
  DATABASE_URL=""
  for base in "postgresql://seo:seo@localhost:5432" "postgresql://${USER:-postgres}@localhost:5432"; do
    if pg_works "$base/postgres"; then DATABASE_URL="$base/$DEMO_DB?schema=public"; break; fi
  done
  [ -n "$DATABASE_URL" ] || fail "No Postgres on localhost:5432. Start one with 'docker compose up -d postgres redis' or './scripts/dev-services.sh', or set DEMO_DATABASE_URL."
fi
ADMIN_URL="${DATABASE_URL%%\?*}"; ADMIN_URL="${ADMIN_URL%/*}/postgres"

if [ "$RESET" = true ] && command -v psql >/dev/null; then
  info "Dropping the demo database"
  psql "$ADMIN_URL" -qc "DROP DATABASE IF EXISTS \"$DEMO_DB\" WITH (FORCE)" >/dev/null
fi
if command -v psql >/dev/null && ! psql "$ADMIN_URL" -tAc "select 1 from pg_database where datname='$DEMO_DB'" | grep -q 1; then
  psql "$ADMIN_URL" -qc "CREATE DATABASE \"$DEMO_DB\"" >/dev/null
  ok "Created database $DEMO_DB"
fi

# ── Throwaway secrets and demo login (kept between runs) ─────────────────────
if [ ! -f "$ENV_FILE" ]; then
  umask 077
  {
    echo "# Generated by scripts/demo.sh for the local demo only. Safe to delete."
    echo "AUTH_SECRET=\"$(openssl rand -base64 48 | tr -d '\n')\""
    echo "ENCRYPTION_KEY=\"$(openssl rand -base64 32 | tr -d '\n')\""
    echo "DEMO_LOGIN_EMAIL=\"demo@seo-os.test\""
    echo "DEMO_LOGIN_PASSWORD=\"Demo-$(openssl rand -hex 8)\""
  } > "$ENV_FILE"
  ok "Generated $ENV_FILE"
fi
set -a
# shellcheck disable=SC1090
. "./$ENV_FILE"
set +a

export DATABASE_URL
export REDIS_URL="${DEMO_REDIS_URL:-redis://localhost:6379/9}"
export APP_URL="http://localhost:$PORT"
export DEMO_MODE=true
export NODE_ENV=production
export NEXT_TELEMETRY_DISABLED=1

# ── Install, migrate, seed ───────────────────────────────────────────────────
[ -d node_modules ] || { info "Installing dependencies"; npm ci --no-audit --no-fund; }
info "Generating the Prisma client"; npm run --silent db:generate >/dev/null
info "Applying migrations"; npm run --silent db:migrate >/dev/null
info "Seeding the labelled demo dataset"
ALLOW_SIGNUP=true SEED_EMAIL="$DEMO_LOGIN_EMAIL" SEED_PASSWORD="$DEMO_LOGIN_PASSWORD" SEED_NAME="Demo Operator" \
  npm run --silent db:seed -- --demo >/dev/null
ok "Demo data ready (three fictional [DEMO] sites)"

# ── Build and serve ──────────────────────────────────────────────────────────
if [ "$REBUILD" = true ] || [ ! -f apps/web/.next/BUILD_ID ]; then
  info "Building the production app (first run takes a few minutes)"
  npm run --silent build >/dev/null
fi

export ALLOW_SIGNUP=false
printf '\n  \033[1mSEO OS demo\033[0m  →  %s\n  email:     %s\n  password:  %s\n\n  Synthetic data only. Stop with Ctrl+C; remove with: npm run demo -- --reset && rm .env.demo\n\n' \
  "$APP_URL" "$DEMO_LOGIN_EMAIL" "$DEMO_LOGIN_PASSWORD"
cd apps/web
exec node ../../node_modules/next/dist/bin/next start -p "$PORT"
